// Regenerates messages/<lang>/index.ts from the JSON files in each folder.
import { readdirSync, writeFileSync } from 'node:fs';
for (const lang of ['de', 'en', 'ls']) {
  const files = readdirSync(`messages/${lang}`).filter((f) => f.endsWith('.json')).sort();
  const lines = files.map((f) => `import ${'ns_' + f.replace('.json', '').replace(/-/g, '_')} from "./${f}";`);
  lines.push('', 'const messages = {', ...files.map((f) => `  ${JSON.stringify(f.replace('.json', ''))}: ${'ns_' + f.replace('.json', '').replace(/-/g, '_')},`), '};', 'export default messages;', '');
  writeFileSync(`messages/${lang}/index.ts`, '// Generated by scripts/messages-index.mjs\n' + lines.join('\n'));
}
